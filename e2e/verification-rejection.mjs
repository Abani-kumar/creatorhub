import { chromium } from 'playwright';
const BASE = process.env.BASE_URL ?? 'http://localhost:3100';
const results = [];
const check = (n, ok, x='') => { results.push(ok); console.log(`${ok?'PASS':'FAIL'}  ${n}${x?'  -> '+x:''}`); };
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
await page.goto(`${BASE}/sign-in`);
await page.getByRole('button', { name: /Sam Rivera/ }).click();
await page.waitForURL('**/dashboard');
await page.evaluate(() => fetch('/api/demo', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action: 'set-verification', status: 'unverified' }) }));
await page.goto(`${BASE}/verification`);
await page.getByRole('heading', { name: 'Your details' }).waitFor();
await page.screenshot({ path: 'e2e/shots/m3a-step1.png' });
// validation: under 18
await page.getByLabel('Full legal name').fill('Sam Rivera');
await page.getByLabel('Date of birth').fill('2015-01-01');
await page.getByLabel('Country', { exact: true }).first().selectOption('US');
await page.getByLabel('Street address').fill('12 Pine Street');
await page.getByLabel('City').fill('Austin');
await page.getByLabel('Postal code').fill('73301');
await page.getByRole('button', { name: /Continue/ }).click();
check('under-18 blocked with message', await page.getByText(/at least 18/).isVisible());
await page.getByLabel('Date of birth').fill('1992-05-14');
await page.getByRole('button', { name: /Continue/ }).click();
await page.getByRole('heading', { name: 'ID document' }).waitFor();
await page.getByRole('button', { name: /Continue/ }).click();
check('step 2 requires type + file', await page.getByText('Choose an ID type').isVisible() && await page.getByText(/Upload a photo or scan/).isVisible());
await page.getByLabel('Passport').check();
await page.locator('input[type=file]').setInputFiles({ name: 'big.jpg', mimeType: 'image/jpeg', buffer: Buffer.alloc(11 * 1024 * 1024) });
check('oversize document rejected', await page.getByText(/10 MB or smaller/).isVisible());
await page.locator('input[type=file]').setInputFiles('e2e/fixtures/passport.jpg');
await page.screenshot({ path: 'e2e/shots/m3b-step2.png' });
await page.getByRole('button', { name: /Continue/ }).click();
await page.getByRole('button', { name: /Start identity check/ }).click();
await page.getByText('Identity check complete').waitFor({ timeout: 10000 });
await page.getByRole('button', { name: /Continue/ }).click();
await page.getByLabel(/I confirm/).check();
await page.screenshot({ path: 'e2e/shots/m3c-review.png' });
await page.getByRole('button', { name: 'Submit for review' }).click();
await page.getByRole('heading', { name: 'Your verification is in review' }).waitFor();
await page.screenshot({ path: 'e2e/shots/m3d-pending.png', fullPage: true });
// reject with custom reason
await page.getByLabel(/Rejection reason/).fill('Photo is cropped; all four corners must show.');
await page.getByRole('button', { name: 'Reject' }).click();
await page.getByText(/wasn.t approved/).first().waitFor();
check('rejection reason shown to creator', await page.getByText('Photo is cropped; all four corners must show.').first().isVisible());
await page.screenshot({ path: 'e2e/shots/m3e-rejected.png', fullPage: true });
check('resubmission starts on step 1 (Your details)', await page.getByRole('heading', { name: 'Your details' }).isVisible());
check('personal details kept for resubmission', (await page.getByLabel('Full legal name').inputValue()) === 'Sam Rivera');
await page.getByRole('button', { name: /Continue/ }).click();
check('document cleared after rejection', !(await page.getByText('passport.jpg').isVisible()));
// can publish gate still holds while rejected
const status = await page.evaluate(async () => { const l = await (await fetch('/api/content?pageSize=50')).json(); const id = l.items[0].id; return (await fetch(`/api/content/${id}/publish`, { method: 'POST' })).status; });
check('publish still blocked while rejected', status === 403 || status === 409, String(status));
console.log(results.filter(Boolean).length + '/' + results.length);
await browser.close();
